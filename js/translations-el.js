window.DISTILLOGIC_I18N=(()=>{
  const textOriginals=new WeakMap();
  const attributeOriginals=new WeakMap();
  const translatedAttributes=['aria-label','placeholder','title'];
  let activeLanguage='en';
  let observer;
  const originalTitle=document.title;

  const normalise=value=>value.replace(/\s+/g,' ').trim();

  const translationFor=value=>{
    const key=normalise(value);
    if(DISTILLOGIC_EL[key])return DISTILLOGIC_EL[key];
    const professionalExperience=key.match(/^(\d+\+?) years of professional experience$/);
    if(professionalExperience)return `${professionalExperience[1]} χρόνια επαγγελματικής εμπειρίας`;
    const years=key.match(/^(\d+\+?) years$/);
    if(years)return `${years[1]} χρόνια`;
    const industryCount=key.match(/^(\d+) industries$/i);
    if(industryCount)return `${industryCount[1]} κλάδοι`;
    const profileCount=key.match(/^(\d+) matching profiles?$/i);
    if(profileCount)return `${profileCount[1]} ${profileCount[1]==='1'?'αντίστοιχο προφίλ':'αντίστοιχα προφίλ'}`;
    return null;
  };

  const translateTextNode=node=>{
    if(!textOriginals.has(node))textOriginals.set(node,node.nodeValue);
    const original=textOriginals.get(node);
    if(activeLanguage==='en'){
      if(node.nodeValue!==original)node.nodeValue=original;
      return;
    }
    const key=normalise(original);
    const translated=translationFor(key);
    if(!translated)return;
    const leading=original.match(/^\s*/)?.[0]||'';
    const trailing=original.match(/\s*$/)?.[0]||'';
    const nextValue=`${leading}${translated}${trailing}`;
    if(node.nodeValue!==nextValue)node.nodeValue=nextValue;
  };

  const translateElementAttributes=element=>{
    let originals=attributeOriginals.get(element);
    if(!originals){
      originals={};
      attributeOriginals.set(element,originals);
    }
    translatedAttributes.forEach(attribute=>{
      if(!element.hasAttribute(attribute))return;
      if(!(attribute in originals))originals[attribute]=element.getAttribute(attribute);
      const original=originals[attribute];
      element.setAttribute(attribute,activeLanguage==='el'?(translationFor(original)||original):original);
    });
  };

  const translateTree=root=>{
    if(root.nodeType===Node.TEXT_NODE){
      translateTextNode(root);
      return;
    }
    if(root.nodeType!==Node.ELEMENT_NODE&&root.nodeType!==Node.DOCUMENT_FRAGMENT_NODE)return;
    if(root.nodeType===Node.ELEMENT_NODE)translateElementAttributes(root);
    const walker=document.createTreeWalker(root,NodeFilter.SHOW_ELEMENT|NodeFilter.SHOW_TEXT);
    let current;
    while((current=walker.nextNode())){
      if(current.nodeType===Node.TEXT_NODE)translateTextNode(current);
      else translateElementAttributes(current);
    }
  };

  const observe=()=>{
    if(observer)return;
    observer=new MutationObserver(records=>records.forEach(record=>{
      record.addedNodes.forEach(node=>translateTree(node));
      if(record.type==='characterData')translateTextNode(record.target);
    }));
    observer.observe(document.body,{subtree:true,childList:true,characterData:true});
  };

  const setLanguage=language=>{
    activeLanguage=language==='el'?'el':'en';
    document.documentElement.lang=activeLanguage;
    document.title=activeLanguage==='el'?(DISTILLOGIC_EL[originalTitle]||originalTitle):originalTitle;
    translateTree(document.body);
    observe();
  };

  return Object.freeze({setLanguage});
})();
